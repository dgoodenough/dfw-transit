"""Editable tables for a generated network (texas-transit study/site_parity.md, phase 5).

    python -m metro tables <id> [--years FILE] [--out DIR]

A generated network (generated/<id>/) is written in dfwt's own schema, so it can be edited by hand the way
DFW's network/ is, with the generator as the check rather than the author. This writes the two tables DFW's
plan has that the generator doesn't, as first drafts, and checks the network with dfwt's validator:

  stages.csv       one row per proposed line: a starter stage from its first stop to its last, opening in
                   the year `years` gives it ({line_id: year}, e.g. a statewide schedule's) or the year its
                   segments carry; split a long line into a starter and extensions by hand (dfwt/staging.py)
  service.csv      each proposed line's headway from its opening year (the line planner's, or the mode's
                   default); add rows to run it more often later
  validation.md    dfwt/validate.py's findings (spacing, curves, hairpins, gaps, islands, names), as for DFW

Rerunning keeps hand edits: a line that already has rows in stages.csv or service.csv keeps them.
"""
import collections
import json
import os

from dfwt import config, validate
from dfwt.staging import STAGE_COLS

from . import inputs, model, output

SERVICE_COLS = ["line_id", "from_year", "headway_min", "note"]


def _rows(path):
    return inputs.read_csv(path) if os.path.exists(path) else []


def write(metro_id, years=None, out=None, log=print):
    out = out or inputs.home("generated", metro_id)
    t = {k: _rows(os.path.join(out, k)) for k in inputs.TABLES}
    cfg = config.load()
    names = {r["station_id"]: r["name"] for r in t["stations.csv"]}
    stops = collections.defaultdict(list)
    for r in sorted(t["line_stops.csv"], key=lambda r: (r["line_id"], int(r["seq"]))):
        stops[r["line_id"]].append(r)
    seg_year = {}
    for r in t["line_segments.csv"]:
        seg_year[r["line_id"]] = min(seg_year.get(r["line_id"], 9999), int(r["year_opens"]))
    old_st = _rows(os.path.join(out, "stages.csv"))
    old_sv = _rows(os.path.join(out, "service.csv"))
    kept_st, kept_sv = {r["line_id"] for r in old_st}, {r["line_id"] for r in old_sv}
    st, sv = list(old_st), list(old_sv)
    for ln in t["lines.csv"]:
        lid = ln["line_id"]
        if ln["status"] == "existing" or not stops[lid]:
            continue
        y = (years or {}).get(lid) or seg_year.get(lid, 9999)
        if lid not in kept_st:
            a, b = stops[lid][0]["station_id"], stops[lid][-1]["station_id"]
            st.append({"line_id": lid, "stage": 1, "kind": "starter", "from_stop": a, "to_stop": b, "year_opens": y,
                       "until_year": "", "via_line": "", "headway_min": "", "locked": "",
                       "note": f"draft: the whole line, {names.get(a, a)} to {names.get(b, b)}"})
        if lid not in kept_sv:
            hw = ln.get("headway_min") or cfg["modes"][ln["mode"]]["default_headway_min"]
            sv.append({"line_id": lid, "from_year": y, "headway_min": hw, "note": "draft: the line planner's headway"
                       if ln.get("headway_min") else "draft: the mode's default headway"})
    inputs.write_csv(os.path.join(out, "stages.csv"), st, STAGE_COLS)
    inputs.write_csv(os.path.join(out, "service.csv"), sv, SERVICE_COLS)
    # the validator, on the network as staged
    m = inputs.load(metro_id)
    t2 = dict(t, **{"stages.csv": st, "service.csv": sv})
    with model.projection(m):
        net = output.load_net(t2, cfg, metro_id)
        findings = validate.run(net)
    by = collections.defaultdict(list)
    for sev, code, line, msg in findings:
        if code != "OVER_BUDGET":   # DFW's budget, not the metro's
            by[(sev, code)].append((line, msg))
    order = {"error": 0, "warn": 1, "info": 2}
    L = [f"# Validation: {metro_id}", "",
         "Generated by `python -m metro tables` with dfwt's validator (`dfwt/validate.py`), as DFW Transit's own network "
         "is checked: errors break the model; warnings are worth a look; info is the stop spacing against the standards "
         "(`config.json` standards). The tables here (`stages.csv`, `service.csv`) are first drafts to edit.", "",
         "| Severity | Check | Count |", "|---|---|---|"]
    for (sev, code), xs in sorted(by.items(), key=lambda kv: (order.get(kv[0][0], 3), kv[0][1])):
        L.append(f"| {sev} | {code} | {len(xs)} |")
    for (sev, code), xs in sorted(by.items(), key=lambda kv: (order.get(kv[0][0], 3), kv[0][1])):
        if sev == "info":
            continue
        L += ["", f"## {sev}: {code}", ""] + [f"- {line}: {msg}" for line, msg in xs[:40]] + \
            ([f"- ... and {len(xs) - 40} more"] if len(xs) > 40 else [])
    with open(os.path.join(out, "validation.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    if log:
        log(f"  {metro_id}: stages.csv {len(st)} rows, service.csv {len(sv)}; validation: "
            + (", ".join(f"{sev} {code} {len(xs)}" for (sev, code), xs in sorted(by.items()) if sev != "info") or "clean"))
    return findings


def main(metro_id, years_path=None, out=None):
    years = json.load(open(years_path, encoding="utf-8")) if years_path else None
    return write(metro_id, years, out)
